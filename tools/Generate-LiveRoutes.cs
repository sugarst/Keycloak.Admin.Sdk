#!/usr/bin/env -S dotnet --
#:property TargetFramework=net10.0
#:property PublishAot=false
#:include ScriptSupport.cs
#:include TargetBaseline.cs
#:project ../src/Keycloak.Admin.Sdk/Keycloak.Admin.Sdk.csproj
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Keycloak.Admin.Sdk;

return await ScriptHost.ExecuteAsync(args, "dotnet run --file tools/Generate-LiveRoutes.cs -- [--check]", ["--check"], async ct =>
{
    string root = ScriptHost.RepositoryRoot();
    using var matrix = JsonDocument.Parse(await File.ReadAllTextAsync(Path.Combine(root, "contracts/admin-api-test-matrix.json"), ct));
    var code = new StringBuilder("// <auto-generated: dispatch only; all business inputs/assertions are handwritten />\nusing System.Text.Json;\nusing Keycloak.Admin.Sdk;\ninternal static class LiveRoutes\n{\n    public static Task<AdminResponse> Invoke(KeycloakAdminClient sdk, LiveInput input) => input.Key switch\n    {\n");
    foreach (var endpoint in AdminEndpointCatalog.All)
    {
        string[] names = endpoint.Operation.Split('.');
        string source = await File.ReadAllTextAsync(Path.Combine(root, "src/Keycloak.Admin.Sdk/Generated/" + names[0] + "Api.g.cs"), ct);
        var signature = Regex.Match(source, @"public Task<[^\r\n]+?> " + Regex.Escape(names[1]) + @"\((?<args>[^\r\n]+)\) =>");
        var declarations = Split(signature.Groups["args"].Value).Select(p => Regex.Match(p.Trim(), @"^(?<type>.*?)\s+(?<name>@?\w+)(?:\s*=.*)?$")).ToArray();
        int pathCount = Regex.Matches(endpoint.Path, @"\{[^}]+\}").Count;
        var call = Enumerable.Range(0, pathCount).Select(i => "input.Paths[" + i + "]").ToList();
        var body = declarations.FirstOrDefault(p => p.Groups["name"].Value == "body");
        if (body is not null)
        {
            string type = body.Groups["type"].Value.TrimEnd('?');
            call.Add("body: " + (type == "HttpContent" ? "input.Content()" : "input.Body is null ? null : LiveJson.Read<" + type + ">(input.Body)"));
        }
        var contract = matrix.RootElement.EnumerateArray().Single(p => p.GetProperty("sdkMethod").GetString() == endpoint.Operation);
        foreach (var query in contract.GetProperty("queries").EnumerateArray())
        {
            string wire = query.GetProperty("name").GetString()!, arg = Arg(wire);
            if (declarations.Take(pathCount).Any(p => p.Groups["name"].Value == arg)) arg += "Query";
            string type = declarations.Single(p => p.Groups["name"].Value == arg).Groups["type"].Value.TrimEnd('?');
            string value = type switch { "bool" => "Boolean", "int" => "Integer", "long" => "Long", "double" => "Number", "List<string>" => "Strings", "string" => "Text", _ => throw new InvalidDataException(type) };
            call.Add(arg + ": input." + value + "(" + L(wire) + ")");
        }
        call.Add("cancellationToken: input.Cancellation");
        code.AppendLine($"        {L(Key(endpoint.Method, endpoint.Path))} => Run(async () => await sdk.{endpoint.Operation}({string.Join(", ", call)})),");
    }
    code.AppendLine("        _ => throw new InvalidOperationException(\"No generated SDK operation: \" + input.Key)\n    };\n    private static async Task<AdminResponse> Run(Func<Task<AdminResponse>> invoke) => await invoke();\n}");
    string target = Path.Combine(root, "tests/Keycloak.Admin.Sdk.IntegrationTests/LiveRoutes.g.cs");
    string output = code.ToString().Replace("\r\n", "\n");
    if (args.Contains("--check")) { if (await File.ReadAllTextAsync(target, ct) != output) throw new InvalidDataException("Stale live SDK dispatch."); }
    else await File.WriteAllTextAsync(target, output, ct);
    Console.WriteLine("Live SDK dispatch: " + AdminEndpointCatalog.All.Count);
});
static string L(string value) => JsonSerializer.Serialize(value, new JsonSerializerOptions { TypeInfoResolver = new System.Text.Json.Serialization.Metadata.DefaultJsonTypeInfoResolver() });
static string Key(string method, string path) => method + " " + Regex.Replace(path.TrimEnd('/'), @"\{[^}]+\}", "{}");
static string Arg(string value) { string id = string.Concat(Regex.Matches(value, @"[A-Za-z0-9]+").Select(m => char.ToUpperInvariant(m.Value[0]) + m.Value[1..])); return "@" + char.ToLowerInvariant(id[0]) + id[1..]; }
static IEnumerable<string> Split(string value)
{
    int start = 0, depth = 0;
    for (int i = 0; i < value.Length; i++) { if (value[i] == '<') depth++; else if (value[i] == '>') depth--; else if (value[i] == ',' && depth == 0) { yield return value[start..i]; start = i + 1; } }
    yield return value[start..];
}
