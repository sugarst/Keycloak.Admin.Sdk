static string Id(string name)
{
    string id = string.Concat(Regex.Matches(name, @"[A-Za-z0-9]+").Select(x => char.ToUpperInvariant(x.Value[0]) + x.Value[1..]));
    return id.Length == 0 ? "Value" : char.IsDigit(id[0]) ? "Value" + id : id;
}
static string Arg(string name) => "@" + char.ToLowerInvariant(Id(name)[0]) + Id(name)[1..];
static string Literal(string text) => "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n") + "\"";
static string Normalize(string path) => Regex.Replace(path.TrimEnd('/'), @"\{[^}]+\}", "{}");
string Fixture(JsonNode? schema)
{
    if (schema?["$ref"]?.GetValue<string>() is string reference) return Fixture(schemas[reference.Split('/').Last()]);
    return schema?["type"]?.GetValue<string>() switch
    {
        "string" => "\"value\"", "array" => "[]", "integer" or "number" => "0", "boolean" => "false", _ => "{}"
    };
}
