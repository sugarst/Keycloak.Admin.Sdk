var jsonTypes = new HashSet<string>(StringComparer.Ordinal) { "JsonElement", "TokenResponse" };
string Type(JsonNode? node, bool nullable = false)
{
    if (node is null) return nullable ? "JsonElement?" : "JsonElement";
    string? reference = node["$ref"]?.GetValue<string>()?.Split('/').Last();
    if (reference is not null)
    {
        if (reference == "RawJsonValue") return nullable ? "JsonElement?" : "JsonElement";
        if (schemas[reference] is JsonNode s && s["type"]?.GetValue<string>() is "string") return nullable ? "string?" : "string";
        return Id(reference) + (nullable ? "?" : "");
    }
    string type = node["type"]?.GetValue<string>() switch
    {
        "string" => "string",
        "boolean" => "bool",
        "integer" => node["format"]?.GetValue<string>() == "int64" ? "long" : "int",
        "number" => "double",
        "array" => "List<" + Type(node["items"]) + ">",
        "object" when node["additionalProperties"] is JsonObject props => "Dictionary<string, " + Type(props) + ">",
        _ => "JsonElement"
    };
    return type + (nullable ? "?" : "");
}
