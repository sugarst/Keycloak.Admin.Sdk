#:property TargetFramework=net10.0
#:property PublishAot=false
#:include ../tests/Keycloak.Admin.Sdk.IntegrationTests/LiveEvidence.cs
using System.Security.Cryptography;

if (args.Length != 2) throw new ArgumentException("Usage: Stamp-ValidationInputs <root> <generated-source>");
string root = Path.GetFullPath(args[0]), destination = Path.GetFullPath(args[1]);
string input = LiveEvidence.ValidationFingerprint(root);
string catalog = Convert.ToHexStringLower(SHA256.HashData(File.ReadAllBytes(Path.Combine(root, "contracts/capabilities.json"))));
string code = "// <auto-generated />\ninternal static class FeatureValidationBuildStamp\n{\n"
    + "    public const string InputFingerprint = \"" + input + "\";\n"
    + "    public const string CatalogSha256 = \"" + catalog + "\";\n}\n";
Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
if (!File.Exists(destination) || File.ReadAllText(destination) != code) File.WriteAllText(destination, code);
