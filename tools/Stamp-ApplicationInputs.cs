#!/usr/bin/env -S dotnet --
#:property TargetFramework=net10.0
#:property PublishAot=false
#:include ../tests/Keycloak.Admin.Sdk.IntegrationTests/LiveEvidence.cs

if (args.Length != 2) throw new ArgumentException("Usage: Stamp-ApplicationInputs <root> <generated-source>");
string root = Path.GetFullPath(args[0]), destination = Path.GetFullPath(args[1]);
if (!destination.StartsWith(root.TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
    throw new ArgumentException("Application build stamp must remain inside the repository.");
string code = "// <auto-generated />\nnamespace Keycloak.Admin.Sdk.Protocols;\ninternal static class ApplicationBuildStamp\n{\n"
    + "    internal const string InputFingerprint = \"" + LiveEvidence.ValidationFingerprint(root) + "\";\n}\n";
Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
if (!File.Exists(destination) || File.ReadAllText(destination) != code) File.WriteAllText(destination, code);
