using System.Text.Json;
using System.Text.RegularExpressions;

// Shared by file-based tools, the generator and the integration executable. No runtime SDK dependency.
internal sealed record TargetBaseline(string Version, string Commit, string ArchiveHash, string OpenApiHash,
    string ServerImage, string Platform, string Sdk, string PackageVersion, int Endpoints,
    string PostgresImage, string PostgresVersionNumber, string NativeSdkImage, string NativeRuntimeImage)
{
    public static TargetBaseline Load(string root) => Parse(File.ReadAllText(Path.Combine(root, "contracts/baseline.json")));
    public static TargetBaseline Parse(string json)
    {
        using var document = JsonDocument.Parse(json);
        var b = document.RootElement;
        string[] names = ["schemaVersion", "keycloakVersion", "commit", "sourceArchiveSha256", "openApiSha256", "serverImage", "testedServerPlatform", "sdk", "packageVersion", "discoveredEndpoints", "postgresImage", "postgresVersionNumber", "nativeSdkImage", "nativeRuntimeImage"];
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var property in b.EnumerateObject()) if (!names.Contains(property.Name) || !seen.Add(property.Name)) throw new InvalidDataException("Unknown or duplicate baseline field.");
        string Get(string name) => b.GetProperty(name).GetString() ?? throw new InvalidDataException("Null baseline field: " + name);
        if (b.GetProperty("schemaVersion").GetInt32() != 1) throw new InvalidDataException("Unknown baseline schema.");
        var target = new TargetBaseline(Get("keycloakVersion"), Get("commit"), Get("sourceArchiveSha256"), Get("openApiSha256"),
            Get("serverImage"), Get("testedServerPlatform"), Get("sdk"), Get("packageVersion"), b.GetProperty("discoveredEndpoints").GetInt32(),
            Get("postgresImage"), Get("postgresVersionNumber"), Get("nativeSdkImage"), Get("nativeRuntimeImage"));
        if (!Regex.IsMatch(target.Version, @"^\d+\.\d+\.\d+$") || !Regex.IsMatch(target.Commit, "^[a-f0-9]{40}$")
            || !Regex.IsMatch(target.ArchiveHash, "^[a-f0-9]{64}$") || !Regex.IsMatch(target.OpenApiHash, "^[a-f0-9]{64}$")
            || !Regex.IsMatch(target.ServerImage, "^quay.io/keycloak/keycloak@sha256:[a-f0-9]{64}$")
            || !Regex.IsMatch(target.Sdk, @"^10\.\d+\.\d+$") || !Regex.IsMatch(target.PackageVersion, @"^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$")
            || target.Endpoints <= 0 || target.Platform != "linux/amd64" || !Regex.IsMatch(target.PostgresVersionNumber, @"^\d{6}$")
            || !Regex.IsMatch(target.PostgresImage, @"^postgres:[\w.-]+(?:@sha256:[a-f0-9]{64})?$")
            || !target.NativeSdkImage.StartsWith("mcr.microsoft.com/dotnet/sdk:" + target.Sdk + "-", StringComparison.Ordinal)
            || !Regex.IsMatch(target.NativeRuntimeImage, @"^mcr\.microsoft\.com/dotnet/aspnet:10\.[\w.-]+$"))
            throw new InvalidDataException("Invalid single-target baseline metadata.");
        return target;
    }
    public string Cache(string root) => Path.Combine(root, ".cache/keycloak", Commit);
    public string Source(string root) => Path.Combine(Cache(root), "pinned-source");
    public string Archive(string root) => Path.Combine(Cache(root), "source.tar.gz");
    public string[] DockerBuildArgs => ["--build-arg", "SDK_IMAGE=" + NativeSdkImage];
    public string Props => $"<!-- Generated from contracts/baseline.json; do not edit. -->\n<Project><PropertyGroup><KeycloakTargetVersion>{Version}</KeycloakTargetVersion><Version>{PackageVersion}</Version></PropertyGroup></Project>\n";
    public string TargetSource => $"// <auto-generated from contracts/baseline.json />\nnamespace Keycloak.Admin.Sdk;\npublic static class KeycloakTarget\n{{\n    public const string Version = \"{Version}\";\n    public const string SourceCommit = \"{Commit}\";\n    public const int EndpointCount = {Endpoints};\n}}\n";
}
