#!/usr/bin/env -S dotnet --
#:property TargetFramework=net10.0
#:property PublishAot=false
#:include ScriptSupport.cs
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

return await ScriptHost.ExecuteAsync(args,
    "dotnet run --file tools/Generate-FeatureCatalog.cs -- [--check] [--stamp=<generated-source>]",
    ["--check", .. args.Where(a => a.StartsWith("--stamp=", StringComparison.Ordinal))], async ct =>
{
    string root = ScriptHost.RepositoryRoot();
    using var flagsDoc = JsonDocument.Parse(await File.ReadAllTextAsync(Path.Combine(root, "contracts/application-capability-flags.json"), ct));
    using var capabilitiesDoc = JsonDocument.Parse(await File.ReadAllTextAsync(Path.Combine(root, "contracts/capabilities.json"), ct));
    using var platformDoc = JsonDocument.Parse(await File.ReadAllTextAsync(Path.Combine(root, "contracts/platform-capabilities.json"), ct));

    var flagsRoot = flagsDoc.RootElement;
    if (flagsRoot.GetProperty("schemaVersion").GetInt32() != 1) throw new InvalidDataException("Unsupported application capability flag schema.");
    var mappings = flagsRoot.GetProperty("flags").EnumerateArray()
        .Select(f => (Id: f.GetProperty("id").GetString()!, Capability: f.GetProperty("capability").GetString()!)).ToArray();
    if (mappings.Length == 0 || mappings.Select(m => m.Id).Distinct(StringComparer.Ordinal).Count() != mappings.Length)
        throw new InvalidDataException("Protocol feature flags must be nonempty and unique.");
    if (mappings.Any(m => !m.Id.StartsWith("KeycloakSdk.Protocols.", StringComparison.Ordinal) || string.IsNullOrWhiteSpace(m.Capability)))
        throw new InvalidDataException("Every protocol feature flag must carry a KeycloakSdk.Protocols.* id and a capability family.");
    var capabilityIds = platformDoc.RootElement.GetProperty("applicationCapabilities").EnumerateArray()
        .Select(c => c.GetProperty("id").GetString()!).Distinct(StringComparer.Ordinal).ToHashSet(StringComparer.Ordinal);
    if (!capabilityIds.SetEquals(mappings.Select(m => m.Capability).ToHashSet(StringComparer.Ordinal)))
        throw new InvalidDataException("Protocol feature mapping must cover exactly the pinned application capability families.");

    string[] masters = ["KeycloakSdk.AdminApi", "KeycloakSdk.Protocols"];
    var adminFlags = capabilitiesDoc.RootElement.GetProperty("endpoints").EnumerateArray()
        .Select(e => e.GetProperty("featureId").GetString()!).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
    if (adminFlags.Length == 0 || adminFlags.Intersect(mappings.Select(m => m.Id), StringComparer.Ordinal).Any()
        || adminFlags.Contains(masters[1], StringComparer.Ordinal) || mappings.Any(m => m.Id == masters[1]))
        throw new InvalidDataException("Admin and protocol flag namespaces, and the protocol master switch, must stay disjoint.");

    var protocolFlags = new JsonArray();
    foreach (var (id, capability) in mappings.OrderBy(m => m.Id, StringComparer.Ordinal))
        protocolFlags.Add(new JsonObject { ["id"] = id, ["capability"] = capability });
    string[] all = adminFlags.Concat(masters).Concat(mappings.Select(m => m.Id)).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
    var catalog = new JsonObject
    {
        ["schemaVersion"] = 1,
        ["masterFlags"] = new JsonArray(masters.Select(m => JsonValue.Create(m)).Cast<JsonNode?>().ToArray()),
        ["adminFlags"] = new JsonArray(adminFlags.Select(m => JsonValue.Create(m)).Cast<JsonNode?>().ToArray()),
        ["protocolFlags"] = protocolFlags,
        ["all"] = new JsonArray(all.Select(m => JsonValue.Create(m)).Cast<JsonNode?>().ToArray())
    };
    string json = catalog.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n";

    string stamp = args.SingleOrDefault(a => a.StartsWith("--stamp=", StringComparison.Ordinal))?["--stamp=".Length..]!;
    if (stamp is not null)
    {
        string destination = Path.GetFullPath(stamp);
        if (!destination.StartsWith(root.TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("Generated feature map must remain inside the repository.");
        var code = new StringBuilder("// <auto-generated />\nnamespace Keycloak.Admin.Sdk.Protocols;\ninternal static class ApplicationFeatureMap\n{\n"
            + "    internal static string Resolve(string feature) => feature switch\n    {\n");
        foreach (var (id, capability) in mappings.OrderBy(m => m.Id, StringComparer.Ordinal))
            code.Append("        \"").Append(id).Append("\" => \"").Append(capability).Append("\",\n");
        code.Append("        _ => \"\"\n    };\n}\n");
        Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
        if (!File.Exists(destination) || File.ReadAllText(destination) != code.ToString()) await File.WriteAllTextAsync(destination, code.ToString(), ct);
        Console.WriteLine("PASS generated application feature map: " + mappings.Length + " flags / " + capabilityIds.Count + " capabilities.");
        return;
    }

    string path = Path.Combine(root, "contracts/feature-flag-catalog.json");
    if (args.Contains("--check"))
    {
        if (!File.Exists(path) || JsonNode.DeepEquals(JsonNode.Parse(await File.ReadAllTextAsync(path, ct)), JsonNode.Parse(json)) is false)
            throw new InvalidDataException("Feature flag catalog is stale; run tools/Generate-FeatureCatalog.cs without --check.");
        Console.WriteLine("PASS feature flag catalog: " + all.Length + " flags (" + adminFlags.Length + " admin, " + mappings.Length + " protocol, 2 masters).");
        return;
    }
    await File.WriteAllTextAsync(path, json, ct);
    Console.WriteLine("WROTE feature flag catalog: " + all.Length + " flags (" + adminFlags.Length + " admin, " + mappings.Length + " protocol, 2 masters).");
});
